import { $, $$ } from './utils.js';

const QUESTIONS = [
  ['С какими проектами работает студия?', 'С лендингами, корпоративными сайтами, интерфейсами веб-приложений и MVP. Подход выбирается под задачу, а не наоборот.'],
  ['Можно ли обновить существующий сайт?', 'Да. Сначала разбираем текущие экраны, затем обновляем визуал и структуру, сохраняя то, что уже работает.'],
  ['Будет ли сайт адаптирован под мобильные устройства?', 'Да. Макет проверяется от 320 px до больших мониторов, без горизонтальной прокрутки.'],
  ['Можно ли добавить анимации и интерактивные функции?', 'Можно. Анимации добавляются там, где они помогают понять интерфейс, и отключаются при настройке уменьшения движения.'],
  ['Что потребуется от заказчика?', 'Описание задачи, примеры, которые нравятся, и тексты. Если текстов нет, поможем составить структуру.'],
  ['Как передаются готовые файлы?', 'Исходный код, собранная версия и README с инструкцией по запуску и публикации.'],
  ['Можно ли расширить проект после запуска?', 'Да. Код разбит на небольшие модули, поэтому новые секции и функции добавляются без переписывания.'],
];

export function initFaq() {
  $('#faq').innerHTML = QUESTIONS.map(([q, a], i) =>
    `<div class="fi"><h3><button class="fq" id="q${i}" aria-expanded="false" aria-controls="a${i}">${q}</button></h3>` +
    `<div class="fa" id="a${i}" role="region" aria-labelledby="q${i}"><div><p>${a}</p></div></div></div>`).join('');
  $$('.fq').forEach((b) => b.addEventListener('click', () => {
    const open = b.getAttribute('aria-expanded') === 'true';
    b.setAttribute('aria-expanded', !open);
    $('#' + b.getAttribute('aria-controls')).classList.toggle('o', !open);
  }));
}
